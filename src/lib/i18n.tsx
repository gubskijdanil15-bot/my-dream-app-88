const dict: Record<Lang, Dict> = { en, uk, ru };

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: TranslationKey) => string };

const LangContext = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k) => en[k] });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "uk" || stored === "en") setLangState(stored);
    else if (navigator.language?.toLowerCase().startsWith("uk")) setLangState("uk");
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    window.localStorage.setItem(STORAGE_KEY, l);
  };

  const t = (k: TranslationKey) => dict[lang][k] ?? dict.en[k];

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}
